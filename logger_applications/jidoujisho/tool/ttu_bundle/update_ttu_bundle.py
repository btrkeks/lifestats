#!/usr/bin/env python3
"""Build the sibling ebook reader, or verify its sources and committed bundle."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
YUUNA = HERE.parent.parent
ASSETS = YUUNA / 'assets/ttu-ebook-reader'
LOCK = HERE / 'bundle.lock.json'
PROVENANCE_KEYS = ['path', 'generation', 'dirty', 'sourceHash', 'buildProfile', 'toolchain']
BEGIN = '    # BEGIN ttu-ebook-reader (generated by tool/ttu_bundle/update_ttu_bundle.py)'
END = '    # END ttu-ebook-reader'
DEFAULT_COMMAND = 'pnpm svelte-kit sync && pnpm build'


def run(*args, **kwargs):
    return subprocess.check_output(args, text=True, **kwargs).strip()


def encoded(value):
    return json.dumps(value, indent=2, sort_keys=True) + '\n'


def manifest(root):
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob('*')) if p.is_file() and p.relative_to(root).as_posix() != 'BUNDLE_SOURCE.json'}


def content_hash(files):
    return hashlib.sha256(encoded(files).encode()).hexdigest()


def asset_block(root):
    dirs = [root, *(p for p in root.rglob('*') if p.is_dir())]
    return '\n'.join('    - assets/ttu-ebook-reader/' +
                     (p.relative_to(root).as_posix() + '/' if p != root else '')
                     for p in sorted(dirs))


def pubspec_for(root):
    current = (YUUNA / 'pubspec.yaml').read_text()
    if current.count(BEGIN) != 1 or current.count(END) != 1:
        raise ValueError('pubspec must contain exactly one generated bundle block')
    start, tail = current.split(BEGIN)
    _, end = tail.split(END)
    return start + BEGIN + '\n' + asset_block(root) + '\n' + END + end


def check_output(root, profile):
    for name in ['index.html', 'b.html', 'manage.html', 'settings.html', 'auth.html', '_app/version.json']:
        if not (root / name).is_file():
            raise ValueError(f'Host contract: missing physical {name}')
    version = json.loads((root / '_app/version.json').read_text())['version']
    if not isinstance(version, str) or not version:
        raise ValueError('Host contract: empty bundle version')
    texts = [(p, p.read_text(errors='replace')) for p in root.rglob('*')
             if p.suffix in {'.js', '.html', '.json', '.css', '.map'} and p.name != 'BUNDLE_SOURCE.json']
    if not any('book-content' in s for _, s in texts):
        raise ValueError('Host contract: missing .book-content lookup target')
    if any(b'localhost:3000' in p.read_bytes() for p in root.rglob('*')
           if p.is_file() and p.name != 'BUNDLE_SOURCE.json'):
        raise ValueError('Host contract: localhost:3000 is baked into output')
    if not any(re.search(r'auth\.html\?ttu-init-', s) for _, s in texts):
        raise ValueError('Host contract: missing auth.html? popup URL')
    if any(re.search(r'/auth\?ttu-init-', s) for _, s in texts):
        raise ValueError('Host contract: extensionless auth popup URL')
    if profile['env'].get('VITE_SERVICE_WORKER') == 'off':
        for p, s in texts:
            if re.search(r'(?:serviceWorker|\bsw)\s*(?:\?\.)?\.\s*register\s*\(', s):
                raise ValueError(f'Host contract: service worker registration in {p.relative_to(root)}')
    print(f'Host contracts passed, generation {version}', flush=True)


def source_files():
    fork = YUUNA / '../ebook-reader'
    names = run('git', '-C', str(fork), 'ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', '.')
    return {name: fork / name for name in sorted(set(names.split('\0'))) if name and (fork / name).is_file()}


def source_hash(files):
    return content_hash({name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in files.items()})


def verify(*, allow_dirty=False):
    lock = json.loads(LOCK.read_text())
    if lock['dirty'] and not allow_dirty:
        raise ValueError('Verification requires clean source; regenerate from a clean sibling fork')
    source = json.loads((ASSETS / 'BUNDLE_SOURCE.json').read_text())
    for key in PROVENANCE_KEYS:
        if source[key] != lock[key]:
            raise ValueError(f'BUNDLE_SOURCE.json differs from bundle.lock.json: {key}')
    if source_hash(source_files()) != lock['sourceHash']:
        raise ValueError('Sibling ebook-reader source drift; regenerate the bundle')
    actual = manifest(ASSETS)
    changed = sorted(k for k in actual.keys() | source['files'].keys() if actual.get(k) != source['files'].get(k))
    if changed or content_hash(actual) != source['contentHash']:
        raise ValueError('Bundle content drift: ' + ', '.join(changed))
    if pubspec_for(ASSETS) != (YUUNA / 'pubspec.yaml').read_text():
        raise ValueError('pubspec asset-directory block drift; regenerate the bundle')
    check_output(ASSETS, lock['buildProfile'])
    print(f'VERIFIED {len(actual)} bundled files and exact pubspec directory block')


def build(args):
    lock = json.loads(LOCK.read_text())
    files = source_files()
    dirty = bool(run('git', '-C', str(YUUNA / '../ebook-reader'), 'status', '--porcelain', '--', '.'))
    if dirty and args.verify:
        raise ValueError('Rebuild verification requires a clean sibling fork')
    lock['dirty'] = dirty
    lock['sourceHash'] = source_hash(files)
    profile = lock['buildProfile']
    if args.build_command:
        profile['command'] = args.build_command
    for name in ['VITE_STATIC_ROUTE_SUFFIX', 'VITE_SERVICE_WORKER']:
        if name in os.environ:
            profile['env'][name] = os.environ[name]
    with tempfile.TemporaryDirectory(prefix='ttu-bundle-') as temporary:
        stage = Path(temporary)
        src = stage / 'source'
        for name, original in files.items():
            target = src / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(original, target)
        toolchain = lock['toolchain']
        command = ('set -eu; test "$(node --version)" = "v' + toolchain['node'] + '"; '
                   'npm install --prefix /tmp/ttu-toolchain pnpm@' + toolchain['pnpm'] + '; '
                   'export PATH=/tmp/ttu-toolchain/node_modules/.bin:$PATH; '
                   'test "$(pnpm --version)" = "' + toolchain['pnpm'] + '"; '
                   'pnpm install --frozen-lockfile; cd apps/web; ' + profile['command'])
        docker = ['docker', 'run', '--rm', '--user', f'{os.getuid()}:{os.getgid()}',
                  '-e', 'HOME=/tmp', '-v', f'{src}:/src', '-w', '/src']
        for name, value in sorted(profile['env'].items()):
            docker += ['-e', f'{name}={value}']
        generation_input = {'sourceHash': lock['sourceHash'], 'profile': profile, 'toolchain': toolchain}
        if not lock['generation'].endswith('-' + content_hash(generation_input)[:16]):
            lock['generation'] = lock['sourceHash'][:12] + '-' + content_hash(generation_input)[:16]
        generation = lock['generation']
        docker += ['-e', f'TTU_BUNDLE_GENERATION={generation}',
                   toolchain['image'], 'sh', '-c', command]
        print(f'Building sibling ebook-reader, dirty={dirty}, source={lock["sourceHash"]}', flush=True)
        subprocess.run(docker, check=True)
        output = src / 'apps/web/build'
        check_output(output, profile)
        files = manifest(output)
        source = {key: lock[key] for key in PROVENANCE_KEYS}
        source.update(contentHash=content_hash(files), files=files)
        (output / 'BUNDLE_SOURCE.json').write_text(encoded(source))
        if args.verify:
            verify()
            old = manifest(ASSETS)
            changed = sorted(k for k in old.keys() | files.keys() if old.get(k) != files.get(k))
            if changed:
                raise ValueError('Rebuild drift (possibly nondeterministic files):\n' + '\n'.join(changed))
            print('VERIFIED rebuilt bytes match committed bundle')
        else:
            if ASSETS.exists():
                old = manifest(ASSETS)
                changed = sorted(k for k in old.keys() | files.keys() if old.get(k) != files.get(k))
                print('Changed output files:\n' + '\n'.join(changed), flush=True)
            pubspec = pubspec_for(output)
            subprocess.run(['rsync', '-a', '--delete', str(output) + '/', str(ASSETS) + '/'], check=True)
            (YUUNA / 'pubspec.yaml').write_text(pubspec)
            LOCK.write_text(encoded(lock))
            verify(allow_dirty=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true', help='Compare committed assets, provenance and pubspec without writing')
    parser.add_argument('--rebuild', action='store_true', help='With --verify, rebuild the sibling sources and compare bytes')
    parser.add_argument('--build-command', help='Exact embedded command supplied by the fork stream, run in apps/web')
    args = parser.parse_args()
    if args.verify and not args.rebuild:
        verify()
    else:
        build(args)


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
